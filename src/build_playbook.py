"""Generate the data-driven parts of the playbook from the analysis outputs:
playbook/incident_cards.md and playbook/daily_summary.md (format + a filled example).
The rules and reply templates (price_match_rules.md, response_templates.md) are written by hand.
All figures are SIMULATED (see data/ASSUMPTIONS.md).
"""
from __future__ import annotations

import pandas as pd

from common import OUT, ROOT

SIMO = OUT / "sim"
PB = ROOT / "playbook"


def incident_cards() -> str:
    inc = pd.read_csv(SIMO / "incidents.csv")
    dq = pd.read_csv(SIMO / "dq_issues.csv")
    out = ["# Incident cards", "",
           "> SIMULATED data (seed 42). Not Emerging Travel Group data. Generated by `src/build_playbook.py` "
           "from `data/output/sim/incidents.csv` and `dq_issues.csv`.", "",
           "One card per event found by the monitoring. Same format every time, so the commercial team can read "
           "it in one minute: what happened, the proof, the impact in euros, what to do, who owns it, how we follow it.",
           "Impacts are margin in EUR from the event start to 31 Oct 2026 (negative = margin lost).", ""]
    for r in inc.itertuples():
        out += [f"## {r.event} · {r.title}", "",
                "| | |", "|---|---|",
                f"| **What happened** | {r.what} |",
                f"| **Evidence** | {r.evidence} |",
                f"| **Impact (EUR)** | {r.impact_eur:+,.0f} |",
                f"| **Recommendation** | {r.recommendation} |",
                f"| **Owner** | {r.owner} |",
                f"| **Follow-up** | {r.follow_up} |", ""]
    out += ["## E5 · Data-quality issues (checked before any conclusion)", "",
            "| Issue | From | To | Scope | Rows | Effect if not caught | Action |", "|---|---|---|---|---|---|---|"]
    for r in dq.itertuples():
        out.append(f"| {r.issue} | {'' if pd.isna(r.date_from) else r.date_from} | {'' if pd.isna(r.date_to) else r.date_to} "
                   f"| {r.scope} | {r.rows:,} | {r.effect} | {r.action} |")
    out += ["", "**Owner:** data engineering (feeds) and finance (supplier invoices). "
            "**Follow-up:** `sql/06_data_quality_checks.sql` runs before the daily summary is sent; "
            "the summary is not sent while a check is red.", ""]
    return "\n".join(out)


def daily_summary() -> str:
    d = pd.read_csv(SIMO / "daily_total.csv", parse_dates=["booking_date"]).set_index("booking_date")
    day = pd.Timestamp("2026-09-15")
    r = d.loc[day]
    al = pd.read_csv(SIMO / "alerts.csv")
    al = al[al["date"] == str(day.date())]
    bp = pd.read_csv(SIMO / "daily_by_partner_type.csv", parse_dates=["booking_date"])
    week = bp[bp["booking_date"].between(day - pd.Timedelta(days=6), day)].groupby("partner_type")["sales_eur"].sum()
    prev = bp[bp["booking_date"].between(day - pd.Timedelta(days=13), day - pd.Timedelta(days=7))].groupby("partner_type")["sales_eur"].sum()
    wk = (week / prev - 1).sort_values()
    lines = [
        "# Daily summary for the commercial team", "",
        "> SIMULATED data (seed 42). Not Emerging Travel Group data. The example below is generated by "
        "`src/build_playbook.py` from `data/output/sim/`.", "",
        "## Format (5 blocks, readable in 2 minutes, sent before 10:00)", "",
        "1. **Data status** - green / red. If red, say which check failed and that numbers are provisional.",
        "2. **Yesterday in one line** - bookings, sales, margin rate vs expected (same weekday, last 4 weeks) and vs last year.",
        "3. **Alerts** - only segments outside the band (|z| >= 3.5), each with a first explanation or \"under review\".",
        "4. **Week trend** - last 7 days vs the 7 before, by partner type; the top 3 partner moves (sql/04).",
        "5. **Actions and owners** - what was decided, who does it, when we check again.",
        "",
        "Rules: numbers rounded; one idea per line; no alert without a next step; market specifics (holidays, events) "
        "from the market calendar before calling something an anomaly.", "",
        f"## Example - summary of {day:%A %d %B %Y}, sent the next morning", "",
        "**1. Data status:** green (duplicates, missing costs, time shift, FX: all checks passed).", "",
        f"**2. {day:%a %d %b}:** {r['bookings']:,.0f} bookings ({r['bookings'] / r['bookings_expected'] - 1:+.0%} vs expected, "
        f"{r['bookings'] / r['bookings_ly'] - 1:+.0%} vs last year), sales €{r['sales_eur']:,.0f} "
        f"({r['sales_eur'] / r['sales_eur_expected'] - 1:+.0%} vs expected), margin rate {r['margin_rate']:.1%} "
        f"(expected {r['margin_rate_expected']:.1%}).", "",
        "**3. Alerts:** " + ("none at total or segment level." if al.empty else
                            "; ".join(f"{a.dimension} {a.member} {a.metric} (z {a.z:+.1f})" for a in al.itertuples())), "",
        "**4. Week trend (sales, last 7 days vs previous 7):** "
        + ", ".join(f"{k} {v:+.0%}" for k, v in wk.items()) + ". "
        "Largest partner move: API-002 (top API partner) at zero since 14 Sep - see incident E2.", "",
        "**5. Actions:** key account manager calls API-002 today (owner: KAM, check Friday); pricing compares our rates "
        "on its top 50 hotels (owner: pricing analyst, tomorrow); Spain margin on Bedbank C still below floor "
        "- supply to confirm re-routing (owner: contracting, Thursday).", "",
    ]
    return "\n".join(lines)


def main() -> None:
    PB.mkdir(exist_ok=True)
    (PB / "incident_cards.md").write_text(incident_cards(), encoding="utf-8", newline="\n")
    (PB / "daily_summary.md").write_text(daily_summary(), encoding="utf-8", newline="\n")
    print("playbook written")


if __name__ == "__main__":
    main()
